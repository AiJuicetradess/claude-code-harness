"""Regenerate LESSONS.md from individual lesson files.

Rules:
  - Promote: times_violated >= 5 -> severity = critical
  - Enforced: status == enforced (set by /reflect escalation rung when a hook
    covers the rule) -> excluded from tiers, named in a header line instead
  - Internalize: times_violated == 0 AND last_triggered > 30d ago -> status = internalized
  - Archive: status == internalized for > 90d -> move file
  - Reactivate: internalized but recently triggered -> active, severity = high
  - Sort active: critical > high > standard, then by times_violated desc
  - Top 20 to LESSONS.md
"""

import io
import re
import sys
from datetime import date, datetime, timedelta
from pathlib import Path

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

LESSONS_DIR = Path.home() / ".claude" / "lessons"
ARCHIVE_DIR = LESSONS_DIR / "archive"
TODAY = date.today()
SEVERITY_ORDER = {"critical": 0, "high": 1, "standard": 2}


def parse_frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.DOTALL)
    if not m:
        return None, text
    fm = {}
    for line in m.group(1).splitlines():
        if ":" not in line:
            continue
        k, _, v = line.partition(":")
        fm[k.strip()] = v.strip().strip('"')
    return fm, text[m.end():]


def fmt_frontmatter(fm):
    keys = ["id", "title", "category", "severity", "status", "created",
            "last_triggered", "times_violated", "times_checked", "tags",
            "related_skills"]
    lines = ["---"]
    for k in keys:
        if k in fm:
            v = fm[k]
            if k in ("title",) and not v.startswith('"'):
                v = f'"{v}"'
            lines.append(f"{k}: {v}")
    for k, v in fm.items():
        if k not in keys:
            lines.append(f"{k}: {v}")
    lines.append("---")
    return "\n".join(lines)


def parse_date(s):
    s = (s or "").strip()
    if not s:
        return None
    for fmt in ("%Y-%m-%d", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M:%SZ"):
        try:
            return datetime.strptime(s, fmt).date()
        except ValueError:
            continue
    return None


def days_since(d):
    if d is None:
        return None
    return (TODAY - d).days


lessons = []
for p in sorted(LESSONS_DIR.glob("L*.md")):
    text = p.read_text(encoding="utf-8")
    fm, body = parse_frontmatter(text)
    if not fm:
        print(f"SKIP (no frontmatter): {p.name}", file=sys.stderr)
        continue
    fm["__path"] = p
    fm["__body"] = body
    fm["__times_violated"] = int(fm.get("times_violated", 0) or 0)
    fm["__last_triggered"] = parse_date(fm.get("last_triggered", ""))
    fm["__days_since_trigger"] = days_since(fm["__last_triggered"])
    lessons.append(fm)

# Apply rules
changed = []
for L in lessons:
    tv = L["__times_violated"]
    sev = L.get("severity", "standard")
    status = L.get("status", "active")
    days = L["__days_since_trigger"]

    # Reactivate: internalized but recently violated (within 30d)
    if status == "internalized" and tv > 0 and days is not None and days < 30:
        L["status"] = "active"
        L["severity"] = "high"
        changed.append(("reactivated", L["id"]))

    # Promote: >=5 violations -> critical
    if tv >= 5 and L.get("severity") != "critical" and L.get("status", "active") == "active":
        L["severity"] = "critical"
        changed.append(("promoted", L["id"]))

    # Internalize: 0 violations and >30d since trigger
    if tv == 0 and days is not None and days > 30 and L.get("status", "active") == "active":
        L["status"] = "internalized"
        changed.append(("internalized", L["id"]))

# Archive: status=internalized for >90d
archived = []
for L in lessons:
    if L.get("status") == "internalized" and L["__days_since_trigger"] is not None and L["__days_since_trigger"] > 90:
        # Don't auto-archive in this script — flag for review
        archived.append(L["id"])

# Write changes back to lesson files
for L in lessons:
    new_fm = {k: v for k, v in L.items() if not k.startswith("__")}
    new_text = fmt_frontmatter(new_fm) + "\n" + L["__body"]
    if new_text != L["__path"].read_text(encoding="utf-8"):
        L["__path"].write_text(new_text, encoding="utf-8")

# Sort active lessons
active = [L for L in lessons if L.get("status", "active") == "active"]
internalized = [L for L in lessons if L.get("status") == "internalized"]
enforced = [L for L in lessons if L.get("status") == "enforced"]

active.sort(key=lambda L: (SEVERITY_ORDER.get(L.get("severity", "standard"), 9),
                            -L["__times_violated"]))

# Build LESSONS.md
out = []
out.append("# Active Lessons (auto-generated by /reflect)")
out.append(f"> Last reflection: {TODAY.isoformat()} | Active: {len(active)} | Internalized: {len(internalized)} | Enforced: {len(enforced)}")
if enforced:
    ids = ", ".join(L["id"] for L in enforced)
    out.append(f"> Hook-enforced (not listed; hooks do the work): {ids}")
out.append("")

# Show all active lessons, capped at ~3KB by truncating titles if needed.
# Skill says "top 20" but file budget is "~3KB" — when all-active fits,
# prefer showing all so newly-created lessons are visible until they earn violations.
current_sev = None
SIZE_BUDGET = 3000  # bytes
running_size = sum(len(s) + 1 for s in out)
truncated = 0
for L in active:
    sev = L.get("severity", "standard")
    if sev != current_sev:
        out.append("")
        out.append(f"## {sev.capitalize()}")
        current_sev = sev
        running_size += len(out[-1]) + len(out[-2]) + 2
    title = L.get("title", "?").strip('"')
    # Truncate long titles to keep the index scannable
    if len(title) > 90:
        title = title[:87] + "..."
    cat = L.get("category", "?")
    line = f"- **{L['id']}** [{cat}] {title} (violations: {L['__times_violated']})"
    if running_size + len(line) + 1 > SIZE_BUDGET:
        truncated += 1
        continue
    out.append(line)
    running_size += len(line) + 1

if internalized:
    out.append("")
    out.append("## Internalized (0 violations 30+ days)")
    for L in internalized:
        title = L.get("title", "?").strip('"')
        cat = L.get("category", "?")
        out.append(f"- ~~{L['id']} [{cat}] {title}~~")

(LESSONS_DIR / "LESSONS.md").write_text("\n".join(out) + "\n", encoding="utf-8")

# Report
print(f"=== REGENERATION SUMMARY ===")
print(f"Total lessons: {len(lessons)} (active: {len(active)}, internalized: {len(internalized)})")
print(f"Changes applied: {len(changed)}")
for kind, id_ in changed:
    print(f"  {kind}: {id_}")
if archived:
    print(f"Candidates for archive (>90d internalized): {archived}")
print()
print(f"LESSONS.md size: {(LESSONS_DIR / 'LESSONS.md').stat().st_size} bytes")
